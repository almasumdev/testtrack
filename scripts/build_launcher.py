"""Export the approved robot as adaptive, themed and legacy launcher icons.

python scripts/build_launcher.py
python scripts/build_launcher.py --raster  # requires playwright, Pillow and an installed Edge
"""
from copy import deepcopy
from pathlib import Path
import argparse
import io
import os
import xml.etree.ElementTree as ET

from build_splash import ANDROID, SVG, android_attrs, build_vector

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
DESIGN = ROOT / "docs/design/logo"
SOURCE = ET.parse(DESIGN / "test-exchange.svg").getroot()


def write(name, vector):
    ET.indent(vector, space="    ")
    (RES / "drawable" / name).write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build_launcher.py. -->\n'
        + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8")


def sized(svg):
    vector = build_vector(svg)
    vector.attrib.update(android_attrs(width="108dp", height="108dp"))
    vector.find("group").attrib.update(android_attrs(scaleX=.74, scaleY=.74))
    return vector


def write_svg(name, source):
    svg = deepcopy(source)
    svg.set("width", "108")
    svg.set("height", "108")
    svg.find(f"{{{SVG}}}g").set("transform", "translate(163.02 163.02) scale(.74)")
    ET.register_namespace("", SVG)
    ET.indent(svg, space="  ")
    (DESIGN / name).write_text(ET.tostring(svg, encoding="unicode") + "\n", encoding="utf-8")


def monochrome():
    svg = deepcopy(SOURCE)
    original = svg.find(f"{{{SVG}}}g")
    by_id = {n.get("id"): n for n in original.iter() if n.get("id")}
    svg.remove(original)
    art = ET.SubElement(svg, f"{{{SVG}}}g", {"id": "monochrome_robot"})

    def add(node):
        node = deepcopy(node)
        if node.get("fill", "none") != "none":
            node.set("fill", "#FFFFFF")
        if node.get("stroke"):
            node.set("stroke", "#FFFFFF")
        art.append(node)

    def outline(outer, inner):
        node = deepcopy(by_id[outer])
        node.set("d", node.get("d") + " " + by_id[inner].get("d"))
        node.set("fill", "#FFFFFF")
        node.set("fill-rule", "evenodd")
        art.append(node)

    for n in list(by_id["antenna"])[:2] + list(by_id["ears"])[:2]:
        add(n)
    outline("head", "face")
    for n in list(by_id["eye_blink"])[:2]:
        add(n)
    add(by_id["smile"])
    for side in ("left", "right"):
        outline(f"card_{side}_shell", f"card_{side}_screen")
        add(by_id[f"check_{side}"])
        add(by_id[f"card_{side}_hand_base"])
    for name in ("top_arrow", "bottom_arrow"):
        node = deepcopy(by_id[name])
        node.attrib.pop("stroke", None)
        add(node)
    vector = sized(svg)
    for n in vector.iter("path"):
        if n.get(f"{{{ANDROID}}}name") in ("head", "card_left_shell", "card_right_shell"):
            n.attrib.update(android_attrs(fillType="evenOdd"))
    svg.remove(svg.find(f"{{{SVG}}}defs"))
    write_svg("launcher-monochrome.svg", svg)
    return vector


def raster():
    from PIL import Image
    from playwright.sync_api import sync_playwright

    # Complete artwork includes the matching gradient and edge decorations.
    svg = ET.parse(DESIGN / "app-icon.svg").getroot()
    ET.register_namespace("", SVG)
    artwork = ET.tostring(svg, encoding="unicode")
    edge = Path(os.environ.get("PROGRAMFILES(X86)", "C:/Program Files (x86)")) / "Microsoft/Edge/Application/msedge.exe"
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=str(edge), headless=True)
        page = browser.new_page(viewport={"width": 192, "height": 192}, device_scale_factor=1)
        for kind, radius in [("ic_launcher", "23%"), ("ic_launcher_round", "50%")]:
            page.set_content('<style>body{margin:0;background:transparent}div{width:192px;height:192px;'
                             f'background:#E9F0F4;border-radius:{radius};overflow:hidden}}'
                             'svg{width:100%;height:100%}</style><div>' + artwork + '</div>')
            img = Image.open(io.BytesIO(page.screenshot(omit_background=True)))
            for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
                img.resize((size, size), Image.Resampling.LANCZOS).save(
                    RES / f"mipmap-{density}" / f"{kind}.webp", lossless=True)
        browser.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raster", action="store_true")
    args = parser.parse_args()
    write("ic_launcher_foreground.xml", sized(SOURCE))
    write_svg("launcher-foreground.svg", SOURCE)
    write("ic_launcher_monochrome.xml", monochrome())
    from build_brand_background import main as build_background
    build_background()
    if args.raster:
        raster()
    print("Updated launcher assets from the approved robot.")
