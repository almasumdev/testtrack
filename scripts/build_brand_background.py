"""Build the gradient launcher background and one complete app-icon SVG."""
from copy import deepcopy
import argparse
import xml.etree.ElementTree as ET

from build_splash import DESIGN, RES, SVG, AAPT, android_attrs


def main(svg_only=False):
    source = ET.parse(DESIGN / "test-exchange.svg").getroot()
    robot = source.find(f"{{{SVG}}}g")
    source.remove(robot)
    defs = source.find(f"{{{SVG}}}defs")
    # A single off-centre light field keeps all visual meaning in the exchange mascot.
    stops = [("0", "#F7FCFF"), ("0.32", "#E7F4FC"), ("0.72", "#B8D8EB"), ("1", "#7FAAC7")]
    gradient = ET.SubElement(defs, f"{{{SVG}}}radialGradient", {
        "id": "icon_ocean_wash", "gradientUnits": "userSpaceOnUse",
        "cx": "455", "cy": "365", "r": "1130",
    })
    for offset, color in stops:
        ET.SubElement(gradient, f"{{{SVG}}}stop", {"offset": offset, "stop-color": color})
    bg = ET.SubElement(source, f"{{{SVG}}}g", {"id": "brand_background"})
    ET.SubElement(bg, f"{{{SVG}}}path", {
        "fill": "url(#icon_ocean_wash)", "d": "M0 0H1254V1254H0Z",
    })
    # Fixed irregular scatter, matching the app. No symbols or checks.
    specs = [(0.06, 0.08, 0.16, -19, 0), (0.59, 0.035, 0.1, 0, 1), (0.86, 0.2, 0.22, 24, 0), (0.37, 0.24, 0.13, -32, 2), (-0.07, 0.36, 0.21, 0, 1), (0.64, 0.43, 0.18, 17, 0), (0.18, 0.54, 0.12, 34, 0), (0.91, 0.59, 0.15, -28, 2), (0.43, 0.69, 0.09, 0, 1), (-0.04, 0.78, 0.18, -12, 0), (0.74, 0.84, 0.2, 29, 0), (0.29, 0.94, 0.16, -23, 2)]
    shapes = []
    for i, (fx, fy, fw, angle, kind) in enumerate(specs):
        x, y, w = fx * 1254, fy * 1254, fw * 1254
        h = w * .38 if kind == 2 else w
        r = w * .25 if kind == 0 else min(w, h) / 2
        d = (f"M{r} 0H{w-r}Q{w} 0 {w} {r}V{h-r}Q{w} {h} {w-r} {h}"
             f"H{r}Q0 {h} 0 {h-r}V{r}Q0 0 {r} 0Z")
        shapes.append((x, y, w, h, angle, d))
        group = ET.SubElement(bg, f"{{{SVG}}}g", {
            "id": f"background_shape_{i}",
            "transform": f"translate({x} {y}) rotate({angle} {w/2} {h/2})",
        })
        ET.SubElement(group, f"{{{SVG}}}path", {
            "d": d, "fill": "#FFFFFF", "fill-opacity": "0.23",
            "stroke": "#FFFFFF", "stroke-opacity": "0.48", "stroke-width": "3",
        })
    if not svg_only:
        vector = ET.Element("vector", android_attrs(
            width="108dp", height="108dp", viewportWidth=1254, viewportHeight=1254,
        ))
        path = ET.SubElement(vector, "path", android_attrs(pathData="M0 0H1254V1254H0Z"))
        attr = ET.SubElement(path, f"{{{AAPT}}}attr", {"name": "android:fillColor"})
        native = ET.SubElement(attr, "gradient", android_attrs(
            type="radial", centerX=455, centerY=365, gradientRadius=1130,
        ))
        for offset, color in stops:
            ET.SubElement(native, "item", android_attrs(offset=offset, color=color))
        for x, y, w, h, angle, d in shapes:
            position = ET.SubElement(vector, "group", android_attrs(translateX=x, translateY=y))
            group = ET.SubElement(position, "group", android_attrs(rotation=angle, pivotX=w/2, pivotY=h/2))
            ET.SubElement(group, "path", android_attrs(
                pathData=d, fillColor="#FFFFFF", fillAlpha=.23,
                strokeColor="#FFFFFF", strokeAlpha=.48, strokeWidth=3,
            ))
        ET.indent(vector, space="    ")
        (RES / "drawable/ic_launcher_background.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build_brand_background.py. -->\n'
            + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8")
    # Export the separate background without unrelated mascot definitions.
    background = deepcopy(source)
    bg_defs = background.find(f"{{{SVG}}}defs")
    for node in list(bg_defs):
        if node.get("id") != "icon_ocean_wash":
            bg_defs.remove(node)
    for tag in ("title", "desc"):
        for node in background.findall(f"{{{SVG}}}{tag}"):
            background.remove(node)
    background.attrib.pop("aria-labelledby", None)
    background.set("width", "512")
    background.set("height", "512")
    ET.register_namespace("", SVG)
    ET.indent(background, space="  ")
    (DESIGN / "app-icon-background.svg").write_text(ET.tostring(background, encoding="unicode") + "\n", encoding="utf-8")
    source.append(deepcopy(robot))
    source.set("width", "512")
    source.set("height", "512")
    ET.register_namespace("", SVG)
    ET.indent(source, space="  ")
    (DESIGN / "app-icon.svg").write_text(ET.tostring(source, encoding="unicode") + "\n", encoding="utf-8")
    print("Updated separate background and combined app-icon SVGs." if svg_only else "Updated SVGs and native launcher background.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--svg-only", action="store_true", help="Leave Android Studio resource imports untouched")
    main(svg_only=parser.parse_args().svg_only)
